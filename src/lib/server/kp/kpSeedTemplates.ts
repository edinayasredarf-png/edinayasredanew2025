/** Извлекает {{плейсхолдеры}} из HTML. */
function placeholders(html: string): string[] {
  const set = new Set<string>();
  for (const m of html.match(/\{\{\s*([a-zA-Z0-9_]+)\s*\}\}/g) || []) set.add(m.replace(/[{}\s]/g, ""));
  return [...set].sort();
}

/** Засеивает готовые шаблоны (по одному разу, без дублей). */
export async function seedKpTemplates(pool: ReturnType<typeof getTimewebPool>): Promise<void> {
  for (const t of TEMPLATES) {
    await pool.query(
      `insert into kp_templates (name, service_type, org_key, filename, data, placeholders, size_bytes, skip_auto_blocks, source, body_html, seed_key)
       values ($1,$2,null,$3,null,$4,0,false,'html',$5,$6)
       on conflict (seed_key) do nothing`,
      [t.name, t.serviceType, `${t.seedKey}.html`, JSON.stringify(placeholders(t.bodyHtml)), t.bodyHtml, t.seedKey]
    );
  }
}
