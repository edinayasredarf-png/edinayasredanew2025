/** Формирует user-часть промпта из готового текста диалога (с ролями и таймкодами). */
export function buildCallAnalysisUser(dialogue: string, context?: {
  managerName?: string | null;
  companyTitle?: string | null;
  dealTitle?: string | null;
}): string {
  const ctxLines: string[] = [];
  if (context?.companyTitle) ctxLines.push(`Компания: ${context.companyTitle}`);
  if (context?.dealTitle) ctxLines.push(`Сделка: ${context.dealTitle}`);
  if (context?.managerName) ctxLines.push(`Менеджер: ${context.managerName}`);
  const ctx = ctxLines.length ? `КОНТЕКСТ:\n${ctxLines.join("\n")}\n\n` : "";
  return `${ctx}ТРАНСКРИПТ РАЗГОВОРА:\n${dialogue}`;
}
