/**
 * Версионированный промпт разметки ролей (Менеджер/Клиент). Аналог шага
 * «Split Roles» из n8n-пайплайна клиента, но с привязкой к idx сегментов
 * (чтобы сохранить таймкоды/выравнивание, а не перегенерировать текст).
 */
export const ROLE_SPLIT_PROMPT_VERSION = "role-split-v1";

export const ROLE_SPLIT_SYSTEM = `Ты размечаешь роли реплик в транскрипте телефонного разговора компании «Единая среда» (цифровизация территорий: инвентаризация зелёных насаждений, кладбищ, ЖКХ, цифровые двойники и т.п.).

Менеджер — сотрудник «Единой среды»: представляет компанию, предлагает услуги, задаёт уточняющие вопросы, называет цены и условия.
Клиент — вторая сторона: отвечает, спрашивает про стоимость/сроки, представляет свою организацию (администрация, УК, предприятие и т.п.).

Тебе дан пронумерованный список реплик (в начале каждой — её номер idx в квадратных скобках). Для КАЖДОЙ реплики определи роль по смыслу и контексту всего диалога: MANAGER, CLIENT или UNKNOWN (если однозначно не ясно).

Учитывай чередование говорящих и то, что STT мог склеить несколько реплик в одну. Верни СТРОГО JSON вида {"roles":[{"idx":0,"role":"MANAGER"},...]} для всех реплик, без пояснений и текста вокруг.`;

/** Пронумерованный список реплик для промпта. */
export function buildRoleSplitUser(
  segments: Array<{ idx: number; text: string }>
): string {
  const lines = segments.map((s) => `[${s.idx}] ${s.text}`).join("\n");
  return `РЕПЛИКИ:\n${lines}`;
}
