// Нормализация «красивого» вида названий компаний и ФИО:
// убираем КАПС, приводим кавычки к ёлочкам «», чистим лишние пробелы.

/** Аббревиатуры (орг.-правовые формы, госорганы) — оставляем ЗАГЛАВНЫМИ. */
const KEEP_UPPER = new Set([
  "ООО", "ОАО", "ЗАО", "ПАО", "АО", "НАО", "ИП", "НКО", "АНО", "НОУ", "ЧОУ",
  "ГУП", "МУП", "ФГУП", "ФГБУ", "ФГКУ", "ФКУ", "ГБУ", "ГКУ", "МБУ", "МКУ",
  "ГАУ", "МАУ", "ГБОУ", "МБОУ", "МАОУ", "МКОУ", "ГБУЗ", "ГАУЗ", "МБУЗ", "МУЗ",
  "МУ", "МО", "РФ", "СНТ", "ТСЖ", "ТСН", "ЖСК", "КФХ", "ФАП", "ЦРБ", "ЖКХ",
  "ТКО", "АИС", "КП", "РЭС", "УК", "ДК", "ДЮСШ", "ЦБ", "ФОК", "ЦКР", "ИНН", "ОГРН",
]);

/** Служебные и частые административные общие слова — со строчной (кроме первого слова). */
const LOWER_WORDS = new Set([
  "в", "во", "на", "по", "при", "для", "за", "из", "от", "до", "о", "об", "обо",
  "и", "с", "со", "у", "к", "а", "но", "же", "ли", "имени", "им", "года",
  // административные единицы (обычно со строчной внутри названия):
  "муниципальный", "муниципального", "муниципальное", "муниципальном", "муниципальная", "муниципальной",
  "район", "района", "районе", "районный", "районного",
  "сельский", "сельского", "сельское", "сельском", "сельсовет", "сельсовета",
  "поселение", "поселения", "поселении",
  "городской", "городского", "городское", "городском", "городского",
  "край", "края", "крае", "область", "области", "областной", "областного",
  "округ", "округа", "округе", "округу",
  "автономный", "автономного", "автономная", "автономной", "автономное", "автономном",
  "город", "города", "село", "села", "деревня", "деревни", "посёлок", "посёлка", "поселок", "поселка", "станица", "станицы", "хутор",
]);

const isInitials = (w: string): boolean => /^[А-ЯЁA-Zа-яёa-z]\.(?:[А-ЯЁA-Zа-яёa-z]\.)*$/.test(w);
const up = (s: string) => s.toLocaleUpperCase("ru");
const low = (s: string) => s.toLocaleLowerCase("ru");

/** Слово с заглавной, части через дефис — каждая с заглавной (кроме служебных). */
function capWord(w: string): string {
  return w
    .split("-")
    .map((p, i) => {
      if (!p) return p;
      const l = low(p);
      if (i > 0 && LOWER_WORDS.has(l)) return l;
      return up(l.charAt(0)) + l.slice(1);
    })
    .join("-");
}

/** Любые кавычки → парные «ёлочки», лишние пробелы у кавычек убираем. */
function normalizeQuotes(s: string): string {
  let open = true;
  let out = s.replace(/["“”„«»]/g, () => {
    const q = open ? "«" : "»";
    open = !open;
    return q;
  });
  out = out.replace(/«\s+/g, "«").replace(/\s+»/g, "»"); // пробелы внутри кавычек
  out = out.replace(/([A-Za-zА-ЯЁа-яё0-9])«/g, "$1 «"); // пробел перед « после буквы/цифры
  return out;
}

function transformWord(w: string, first: boolean): string {
  if (isInitials(w)) return up(w);
  const bare = up(w.replace(/\./g, ""));
  if (KEEP_UPPER.has(bare)) return up(w);
  const l = low(w);
  if (!first && LOWER_WORDS.has(l)) return l;
  return capWord(w);
}

/** Красивое название компании: ООО «Сфера», без КАПСА и «прямых» кавычек. */
export function normalizeCompanyName(input: string): string {
  let s = (input || "").trim().replace(/\s+/g, " ");
  if (!s) return s;
  // Снять кавычки, обёрнутые вокруг ВСЕГО названия (мусор из Bitrix), — но не
  // трогать бренд в кавычках вроде ООО «Ромашка» (там строка не начинается с кавычки).
  while (s.length > 2 && /^["«»“”„]/.test(s) && /["«»“”„]$/.test(s)) {
    s = s.slice(1, -1).trim();
  }
  s = normalizeQuotes(s);
  let first = true;
  s = s.replace(/[A-Za-zА-ЯЁа-яё][A-Za-zА-ЯЁа-яё.]*(?:-[A-Za-zА-ЯЁа-яё.]+)*/g, (w) => {
    const res = transformWord(w, first);
    first = false;
    return res;
  });
  return s;
}

/** Красивое ФИО: Иванов Иван Иванович (каждое слово с заглавной, инициалы — как есть). */
export function normalizeFio(input: string): string {
  const s = (input || "").trim().replace(/\s+/g, " ");
  if (!s) return s;
  return s.replace(/[A-Za-zА-ЯЁа-яё][A-Za-zА-ЯЁа-яё.]*(?:-[A-Za-zА-ЯЁа-яё.]+)*/g, (w) =>
    isInitials(w) ? up(w) : capWord(w)
  );
}
